"""Generate the mentor presentation from the real project results.

Produces two deliverables:

* ``Project_7_Digo_Presentation.pptx`` - the slide deck
* ``PROJECT_PRESENTATION.md``          - the same deck as a written plan

Every number in both is read from the artifacts the notebook produced -
``models/model_metadata.json`` and ``reports/model_comparison.csv`` - and every
chart is a PNG generated by the notebook. Nothing is typed in by hand, so the
slides cannot drift away from the actual results.

Run after the notebook has completed::

    .venv\\Scripts\\python.exe make_presentation.py
"""

