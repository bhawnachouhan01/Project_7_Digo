SLIDE_WIDTH = Inches(13.333)
SLIDE_HEIGHT = Inches(7.5)

EMU_PER_INCH = 914400
#: Lowest point any content may reach, leaving a small bottom margin.
SAFE_BOTTOM = 7.2


def load_results() -> tuple[dict, pd.DataFrame]:
    """Load the real metadata and comparison table, or exit with guidance."""
    if not METADATA_FILE.exists() or not COMPARISON_FILE.exists():
        sys.exit(
            "Results not found. Run notebooks/Project_7_Digo_NLP.ipynb first - "
            "this script only formats results that already exist."
        )
    with open(METADATA_FILE, encoding="utf-8") as handle:
        metadata = json.load(handle)
    return metadata, pd.read_csv(COMPARISON_FILE)


def add_title(slide, text: str, subtitle: str = "") -> None:
    box = slide.shapes.add_textbox(Inches(0.6), Inches(0.35), Inches(12.1), Inches(1.0))
    frame = box.text_frame
    frame.word_wrap = True
    paragraph = frame.paragraphs[0]
    paragraph.text = text
    paragraph.font.size = Pt(32)
    paragraph.font.bold = True
    paragraph.font.color.rgb = DARK

    if subtitle:
        sub = frame.add_paragraph()
        sub.text = subtitle
        sub.font.size = Pt(14)
        sub.font.color.rgb = MUTED


def add_bullets(slide, bullets, top=1.6, left=0.7, width=12.0, size=16) -> None:
    # Height is clamped to the slide so the text box never extends past the
    # bottom edge (which shows up as a stray frame when editing in PowerPoint).
    box_height = max(0.5, min(5.2, SAFE_BOTTOM - top))
    box = slide.shapes.add_textbox(Inches(left), Inches(top), Inches(width),
                                   Inches(box_height))
    frame = box.text_frame
    frame.word_wrap = True
    for index, item in enumerate(bullets):
        level = 0
        text = item
        if isinstance(item, tuple):
            text, level = item
        paragraph = frame.paragraphs[0] if index == 0 else frame.add_paragraph()
        paragraph.text = ("• " if level == 0 else "– ") + text
        paragraph.level = level
        paragraph.font.size = Pt(size if level == 0 else size - 2)
        paragraph.font.color.rgb = DARK if level == 0 else MUTED
        paragraph.space_after = Pt(9)


def add_image(slide, filename: str, left=1.5, top=1.6, width=10.3,
              max_bottom=6.45, center=True) -> bool:
    """Place a figure, shrinking it if it would run off the slide.

    python-pptx derives the height from the image's aspect ratio, so asking for a
    width that *looks* reasonable can still produce a picture taller than the
    7.5-inch slide. This helper measures the resulting height and, if it would
    cross ``max_bottom`` (which leaves room for the caption added by
    :func:`add_note`), scales the picture down and re-centres it horizontally.
    """
    path = FIGURES_DIR / filename
    if not path.exists():
        return False

    picture = slide.shapes.add_picture(str(path), Inches(left), Inches(top),
                                       width=Inches(width))
    height = picture.height / EMU_PER_INCH

    available = max_bottom - top
    if height > available:
        scale = available / height
        picture.width = Inches(width * scale)
        picture.height = Inches(height * scale)
        if center:
            picture.left = Inches((SLIDE_WIDTH / EMU_PER_INCH - width * scale) / 2)
    return True


def add_note(slide, text: str, top=6.55) -> None:
    box = slide.shapes.add_textbox(Inches(0.7), Inches(top), Inches(12.0), Inches(0.6))
    frame = box.text_frame
    frame.word_wrap = True
    paragraph = frame.paragraphs[0]
    paragraph.text = text
    paragraph.font.size = Pt(11)
    paragraph.font.italic = True
    paragraph.font.color.rgb = MUTED


def add_table(slide, frame: pd.DataFrame, left=0.7, top=1.7, width=11.9, height=4.4,
              font_size=11) -> None:
    rows, columns = frame.shape[0] + 1, frame.shape[1]
    shape = slide.shapes.add_table(rows, columns, Inches(left), Inches(top),
                                   Inches(width), Inches(height))
    table = shape.table

    for column_index, name in enumerate(frame.columns):
        cell = table.cell(0, column_index)
        cell.text = str(name)
        paragraph = cell.text_frame.paragraphs[0]
        paragraph.font.size = Pt(font_size)
        paragraph.font.bold = True
        paragraph.font.color.rgb = WHITE
        cell.fill.solid()
        cell.fill.fore_color.rgb = ACCENT

    for row_index, (_, row) in enumerate(frame.iterrows(), start=1):
        for column_index, value in enumerate(row):
            cell = table.cell(row_index, column_index)
            cell.text = str(value)
            paragraph = cell.text_frame.paragraphs[0]
            paragraph.font.size = Pt(font_size)
            paragraph.font.color.rgb = DARK
            if column_index > 0:
                paragraph.alignment = PP_ALIGN.CENTER


def build_cover_slide(slide, metadata: dict, metrics: dict) -> None:
    """Title slide.

    Keeps the deck's existing light styling and palette; only the *information*
    is laid out like a formal submission cover - organisation and programme,
    title, one-line description, headline result, then the prepared-by line.
    """
    def text_block(left, top, width, height):
        box = slide.shapes.add_textbox(Inches(left), Inches(top),
                                       Inches(width), Inches(height))
        box.text_frame.word_wrap = True
        return box.text_frame

    # --- eyebrow: organisation and programme ---
    frame = text_block(0.9, 1.75, 11.5, 0.4)
    eyebrow = frame.paragraphs[0]
    eyebrow.text = f"{COVER['organisation']}  •  {COVER['programme']}"
    eyebrow.font.size = Pt(13)
    eyebrow.font.bold = True
    eyebrow.font.color.rgb = ACCENT

    # --- title, two lines ---
    frame = text_block(0.9, 2.3, 11.5, 1.8)
    for index, line in enumerate((COVER["title_line_1"], COVER["title_line_2"])):
        paragraph = frame.paragraphs[0] if index == 0 else frame.add_paragraph()
        paragraph.text = line
        paragraph.font.size = Pt(40)
        paragraph.font.bold = True
        paragraph.font.color.rgb = DARK
        paragraph.line_spacing = 1.1

    # --- one-line description ---
    frame = text_block(0.9, 4.25, 11.3, 1.0)
    subtitle = frame.paragraphs[0]
    subtitle.text = COVER["subtitle"]
    subtitle.font.size = Pt(14)
    subtitle.font.color.rgb = MUTED
    subtitle.line_spacing = 1.35

    # --- headline result, so the cover states the outcome ---
    if metrics:
        frame = text_block(0.9, 5.45, 11.3, 0.4)
        result = frame.paragraphs[0]
        result.text = (
            f"Final model: {metadata.get('model_name', 'n/a')}   •   "
            f"Accuracy {metrics['accuracy']:.1%}   •   F1 {metrics['f1']:.3f}"
        )
        result.font.size = Pt(13)
        result.font.bold = True
        result.font.color.rgb = ACCENT

    # --- prepared-by line ---
    frame = text_block(0.9, 6.5, 11.3, 0.4)
    byline = frame.paragraphs[0]
    byline.text = (
        f"Prepared by {COVER['author']}  |  {COVER['project_number']}  |  "
        f"{COVER['submission']}  |  {COVER['date']}"
    )
    byline.font.size = Pt(12.5)
    byline.font.color.rgb = MUTED


